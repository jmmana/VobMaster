def load_existing():
    with open("src/data/words.ts", "r", encoding="utf-8") as f:
        content = f.read()
    eq_idx = content.find("= [")
    json_str = content[eq_idx + 2 : content.rfind("]") + 1]
    return json.loads(json_str)

def main():
    existing = load_existing()
    print(f"Current database count: {len(existing)}")
    seen = {w["word"].lower().strip(): True for w in existing}

    new_items = []

    # Import existing batch modules
    from fresh_lexicon_1200 import FRESH_WORDS
    for entry in FRESH_WORDS:
        w, es, lvl, ipa, ex, exEs, emo, cat_id = entry
        clean_w = w.strip()
        key = clean_w.lower()
        if key not in seen:
            seen[key] = True
            meta = category_meta.get(cat_id, category_meta["verbs_action"])
            new_items.append({
                "word": clean_w,
                "translation": es.strip(),
                "level": lvl.strip(),
                "category": meta["name"],
                "categoryId": cat_id,
                "phonetic": ipa.strip(),
                "example": ex.strip(),
                "exampleEs": exEs.strip(),
                "emoji": emo.strip(),
                "visualColor": meta["color"]
            })

    print(f"New items added from fresh_lexicon: {len(new_items)}")
    print(f"Subtotal words: {len(existing) + len(new_items)}")

if __name__ == "__main__":
    main()
